// 音乐基础数据生成（不依赖 MB 实时搜索，稳定可交付）
// 从 seeds-music 提取真实专辑/艺术家名生成卡片；MB 实时元数据作为增强（若可用）
// 生成 lib/media/generated-music.ts（保证静态站点有真实条目内容）
import { writeFileSync as wf, mkdirSync as mk } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const { MUSIC_THEMES } = await import('../lib/media/seeds-music.ts');

const items = [];
const seen = new Set();
for (const t of MUSIC_THEMES) {
  for (const name of t.items) {
    if (seen.has(name)) continue;
    seen.add(name);
    items.push({
      source: 'music',
      refId: `seed-${seen.size}`,
      title: name,
      creator: '', // MB 增强时填充
      year: '',
      tags: t.tags,
      cover: null,
      url: `/music/${t.slug}`,
    });
  }
}

const ts = `// AUTO-GENERATED by scripts/gen-music-seed.mjs (seed-based, MB-enhanced separately)\nimport type { CurationItem } from './musicbrainz';\nexport const MUSIC_ITEMS: CurationItem[] = ${JSON.stringify(items, null, 2)};\n`;
wf(join(ROOT, 'lib', 'media', 'generated-music.ts'), ts);
console.log(`Generated ${items.length} music seed cards → generated-music.ts`);
