// 构建期数据管道：为每款游戏抓取 Steam 英文高赞用户评测，生成真实口碑驱动的 Our take
// 目的：打破模板化 editorialNotes（"arrives early on purpose" 互相复制），用真实玩家声音差异化
// 数据源：Steam appreviews API（无需 key、无限流、代理可达）
// 生成 lib/media/steam-reviews.ts（映射 refId -> {scoreDesc, positive, total, pct, topReview, topVotes}）
import { execFileSync } from 'node:child_process';
import { writeFileSync as wf, mkdirSync as mk, existsSync as ex, readFileSync as rf } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const CACHE_DIR = join(ROOT, 'cache');
const OUT = join(ROOT, 'lib', 'media', 'steam-reviews.ts');
mk(CACHE_DIR, { recursive: true });
const CACHE = join(CACHE_DIR, 'steam-reviews.json');
let cache = ex(CACHE) ? JSON.parse(rf(CACHE, 'utf8')) : {};
const save = () => wf(CACHE, JSON.stringify(cache, null, 2));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const CURL = 'C:/Windows/system32/curl.exe';

function curlRaw(args, attempt = 1) {
  try { return execFileSync(CURL, args, { encoding: 'utf8', maxBuffer: 20 * 1024 * 1024, timeout: 25000 }); }
  catch { if (attempt >= 3) throw new Error('curl fail'); return curlRaw(args, attempt + 1); }
}

// 清洗评测：去控制符、折叠空白、截到句号边界
function clean(review) {
  return (review || '')
    .replace(/[\u0000-\u001f\u2028\u2029]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
function pickBest(reviews) {
  // 过滤：>90 字符、含空格（非纯情绪词）、非全大写玩梗
  const ok = (reviews || []).filter((r) => {
    const t = clean(r.review);
    return t.length > 90 && t.length < 600 && /[a-z]{4,}/.test(t) && !/^(LOL|lmao|kek|based|mid|trash|dogshit|10\/10|0\/10)\b/i.test(t);
  });
  if (!ok.length) return null;
  // 按 votes_up 降序取第一条有意义的
  ok.sort((a, b) => (b.votes_up || 0) - (a.votes_up || 0));
  const r = ok[0];
  let t = clean(r.review);
  if (t.length > 320) t = t.slice(0, 317).replace(/\s+\S*$/, '') + '…';
  return { text: t, votes: r.votes_up || 0, playtime: Math.round((r.playtime_at_review || 0) / 60) };
}

async function fetchOne(appid, attempt = 1) {
  await sleep(300);
  const url = `https://store.steampowered.com/appreviews/${appid}?json=1&language=english&num_per_page=8&review_type=all&purchase_type=all`;
  let txt;
  try { txt = curlRaw(['-sL', '--max-time', '20', url], attempt); }
  catch (e) { if (attempt >= 3) throw e; await sleep(1200); return fetchOne(appid, attempt + 1); }
  try {
    const j = JSON.parse(txt);
    if (j.success !== 1) return null;
    const q = j.query_summary || {};
    const pos = q.total_positive || 0, total = q.total_reviews || 0;
    const pct = total ? Math.round((pos / total) * 100) : 0;
    const best = pickBest(j.reviews);
    return {
      scoreDesc: q.review_score_desc || '',
      positive: pos, total, pct,
      topReview: best?.text || null,
      topVotes: best?.votes || 0,
      topPlaytime: best?.playtime || 0,
    };
  } catch { if (attempt >= 3) return null; await sleep(1200); return fetchOne(appid, attempt + 1); }
}

async function main() {
  const { GAME_ITEMS } = await import('../lib/media/generated-games.ts');
  const ids = [...new Set(GAME_ITEMS.map((g) => g.refId).filter(Boolean))];
  console.log(`Games to fetch Steam reviews: ${ids.length} (cached: ${Object.keys(cache).length})`);

  for (const id of ids) {
    if (cache[id]) continue;
    try {
      const r = await fetchOne(id);
      if (r) { cache[id] = r; save(); console.log(`  ✓ ${id}: ${r.scoreDesc} ${r.pct}% (${r.total}) ${r.topReview ? 'review✓' : 'no-review'}`); }
      else { cache[id] = null; save(); console.log(`  ✗ ${id}: no data`); }
    } catch (e) { console.log(`  ✗ error ${id}: ${e.message}`); }
  }

  // 生成 TS 模块
  const entries = Object.entries(cache).filter(([, v]) => v);
  const body = entries.map(([id, v]) => `  ${JSON.stringify(id)}: ${JSON.stringify(v)}`).join(',\n');
  const ts = `// AUTO-GENERATED by scripts/fetch-steam-reviews.mjs — do not edit\n// 真实 Steam 用户口碑（评分摘要 + 高赞英文评测），用于差异化 Our take\nimport type { CurationItem } from './musicbrainz';\nexport type SteamReview = { scoreDesc: string; positive: number; total: number; pct: number; topReview: string | null; topVotes: number; topPlaytime: number };\nexport const STEAM_REVIEWS: Record<string, SteamReview> = {\n${body}\n};\n`;
  wf(OUT, ts);
  const withReview = entries.filter(([, v]) => v.topReview).length;
  console.log(`\nDone. ${entries.length} games with Steam data → ${OUT} (${withReview} have top review)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
