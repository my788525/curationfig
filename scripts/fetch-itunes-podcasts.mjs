// ===== iTunes Search API 抓取脚本（Podcasts 频道）=====
// 真实数据源：Apple iTunes Search API（无需 key，真实播客名/主播/feed/genre）
// 诚信原则：只写入 API 真实返回的元数据，绝不虚构评分/评论。
// 输出：lib/media/generated-podcasts.ts
import { writeFileSync } from 'node:fs';

const ITUNES = 'https://itunes.apple.com/search';

// 真实播客种子（按主题分类）。这些是确有其作的播客，脚本查 iTunes 补全真实元数据。
const SEEDS = {
  'narrative-fiction': {
    title: 'Narrative & Fiction Podcasts',
    items: ['Welcome to Night Vale', 'The Magnus Archives', 'Homecoming', 'Alice Isn’t Dead', 'Limetown', 'The Bright Sessions', 'Within the Wires', 'The Truth', 'Passing Strangers'],
  },
  'film-tv-recaps': {
    title: 'Film & TV Dissection Podcasts',
    items: ['How Did This Get Made?', 'Blank Check with Griffin & David', 'The Rewatchables', 'Scriptnotes', 'You Must Remember This', 'The Big Picture', 'Watch What Crappens', 'Pop Culture Happy Hour'],
  },
  'game-interviews': {
    title: 'Games & Developer Podcasts',
    items: ['Giant Bombcast', 'The Game Informer Show', 'Waypoint Radio', 'Kinda Funny Games Daily', 'The Idle Thumbs Podcast', 'Designer Notes', 'Triple Click', 'Xbox Expansion Pass'],
  },
  'cultural-storytelling': {
    title: 'Cultural Storytelling & Nonfiction',
    items: ['Serial', 'S-Town', 'Criminal', 'Revisionist History', '99% Invisible', 'Radiolab', 'This American Life', 'Invisibilia', 'Heavyweight', 'Reply All'],
  },
  'comedy-conversation': {
    title: 'Comedy & Conversation Podcasts',
    items: ['My Brother, My Brother and Me', 'Conan O’Brien Needs a Friend', 'The Adventure Zone', 'WTF with Marc Maron', 'SmartLess', 'Office Ladies', 'Call Her Daddy', 'The Joe Rogan Experience'],
  },
};

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

async function itunesSearch(term) {
  const url = `${ITUNES}?term=${encodeURIComponent(term)}&media=podcast&limit=1&country=US`;
  const r = await fetch(url, { headers: { Accept: 'application/json' } });
  if (!r.ok) throw new Error(`HTTP ${r.status}`);
  const j = await r.json();
  return j.results?.[0] || null;
}

async function main() {
  const out = {};
  let count = 0;
  for (const [themeKey, theme] of Object.entries(SEEDS)) {
    for (const name of theme.items) {
      try {
        const m = await itunesSearch(name);
        if (!m) {
          console.log(`  [miss] ${name}`);
          continue;
        }
        const title = m.collectionName || name;
        const creator = m.artistName || '';
        const refId = `itunes:${m.collectionId}`;
        const genre = m.primaryGenreName ? [m.primaryGenreName.toLowerCase().replace(/\s+/g, '-')] : [];
        const meta = {
          source: 'podcasts',
          refId,
          title,
          creator,
          year: undefined,
          tags: ['podcast', ...genre],
          cover: null, // iTunes 封面走 Apple CDN，本环境不可达，诚实置 null
          url: m.feedUrl ? `/podcasts/${slugify(title)}/` : `/podcasts/${slugify(title)}/`,
          seedName: name,
          synopsis: m.feedUrl ? `Hosted by ${creator || 'unknown'}. Genre: ${m.primaryGenreName || 'Podcast'}. Feed: ${m.feedUrl}` : undefined,
        };
        out[name] = meta;
        count++;
        console.log(`  [ok] ${title} — ${creator} (${m.primaryGenreName || '?'})`);
        await new Promise((r) => setTimeout(r, 400));
      } catch (e) {
        console.log(`  [err] ${name}: ${e.message}`);
        await new Promise((r) => setTimeout(r, 1000));
      }
    }
  }
  const file = 'lib/media/generated-podcasts.ts';
  const header = `// AUTO-GENERATED by scripts/fetch-itunes-podcasts.mjs — do not edit by hand.\n// Source: Apple iTunes Search API (https://itunes.apple.com, no key required).\n// Retrieved: 2026-08-24. Real metadata only; no fabricated ratings/reviews.\n// Cover images are intentionally null (Apple CDN unreachable from build env) — cards use no-cover fallback.\n\nexport type GeneratedItem = {\n  source: 'podcasts';\n  refId: string;\n  title: string;\n  creator: string;\n  year?: string;\n  tags: string[];\n  cover: null;\n  url: string;\n  seedName: string;\n  synopsis?: string;\n};\n\nexport const PODCASTS_ITEMS: GeneratedItem[] = [\n`;
  const body = Object.values(out).map((v) => '  ' + JSON.stringify(v)).join(',\n');
  writeFileSync(file, header + body + '\n];\n');
  console.log(`\n== podcasts: wrote ${count} items to ${file} ==\n`);
}

main().catch((e) => {
  console.error('FATAL', e);
  process.exit(1);
});
